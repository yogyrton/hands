        <h1>Положение о подарочных сертификатах</h1>
        <div class="updated">Дата обновления: {{ date('d.m.Y') }}</div>

        <p>Положение о порядке и условиях реализации и использования подарочных сертификатов
            у индивидуального предпринимателя Парусова Егора Васильевича.</p>

        <p>Настоящее Положение разработано на основании Гражданского кодекса Республики Беларусь,
            Закона Республики Беларусь от 09.01.2002 № 90-З «О защите прав потребителей», Положения
            о порядке и условиях реализации товаров (выполнения работ, оказания услуг) по подарочному
            сертификату или иному подобному документу, утвержденного постановлением Совета Министров
            Республики Беларусь от 22.12.2018 № 935 «О некоторых мерах по защите прав потребителей»
            (в редакции постановления Совета Министров Республики Беларусь от 06.02.2026 № 67)
            (далее — Положение № 935), Налогового кодекса Республики Беларусь, и устанавливает порядок
            выпуска, реализации и использования подарочных сертификатов индивидуальным предпринимателем
            Парусовым Егором Васильевичем (далее — Продавец).</p>

        <h2>1. Общие положения</h2>
        <p>1.1. Подарочный сертификат — документ, в том числе в электронном (цифровом) виде,
            удостоверяющий право предъявителя на получение услуг массажа, указанных в сертификате,
            и (или) услуг на сумму, эквивалентную номинальной цене сертификата (п. 2 Положения № 935).</p>
        <p>1.2. Приобретение сертификата является внесением потребителем предварительной оплаты (аванса)
            в счет заключаемого в будущем договора возмездного оказания услуг, в соответствии с общими
            положениями об обязательствах и договорах, установленными Гражданским кодексом Республики
            Беларусь.</p>
        <p>1.3. Продавец выпускает сертификаты двух видов:</p>
        <ul>
            <li>1.3.1. сертификат на определенную денежную сумму (номинал) — предъявитель самостоятельно
                выбирает услуги в пределах указанной суммы;</li>
            <li>1.3.2. сертификат на определенное количество посещений (сеансов) с указанием конкретного
                вида услуги (например, массаж 90 минут, массаж лица и т.п.).</li>
        </ul>

        <h2>2. Обязательные реквизиты сертификата</h2>
        <p>2.1. В соответствии с пунктом 3 Положения № 935 на сертификате (либо путем указания ссылки
            на информационный источник, где это прямо допускается пунктом 3 Положения № 935) до потребителя
            доводится следующая информация:</p>
        <ul>
            <li>а) наименование, место нахождения, учетный номер плательщика (УНП), номер телефона Продавца;</li>
            <li>б) номер телефона для справок по вопросам использования сертификата;</li>
            <li>в) наименование и место нахождения объекта (либо ссылка на информационный источник — сайт,
                аккаунт в Instagram, систему онлайн-записи YCLIENTS), в котором потребитель может
                воспользоваться сертификатом;</li>
            <li>г) наименование услуги (вида массажа) либо указание, что сертификат предоставляет право
                выбора услуг в пределах номинала;</li>
            <li>д) номинальная цена сертификата в белорусских рублях (для сертификатов на сумму);</li>
            <li>е) номер и дата реализации сертификата;</li>
            <li>ж) срок действия сертификата;</li>
            <li>з) порядок и условия использования сертификата либо ссылка на информационный источник,
                содержащий такие условия (настоящее Положение, размещенное в открытом доступе).</li>
        </ul>
        <p>2.2. Продавец обеспечивает указание на бланке сертификата сведений, перечисленных в подпунктах
            «а», «б», «г», «д», «е», «ж» пункта 2.1 настоящего Положения непосредственно на самом
            сертификате, поскольку пункт 3 Положения № 935 не допускает замену этих сведений ссылкой
            на внешний источник. Сведения по подпунктам «в» и «з» могут быть доведены путем указания
            ссылки на информационный источник.</p>

        <h2>3. Порядок оплаты и выдачи сертификата</h2>
        <p>3.1. Оплата сертификата производится наличными либо безналичными денежными средствами
            с обязательным пробитием кассового чека в момент приема денежных средств, в соответствии
            с законодательством Республики Беларусь о порядке использования кассового оборудования
            и Налоговым кодексом Республики Беларусь.</p>
        <p>3.2. Сертификат выдается потребителю после поступления оплаты в полном объеме.</p>

        <h2>4. Порядок использования сертификата</h2>
        <p>4.1. Запись на услугу по сертификату осуществляется через систему онлайн-записи YCLIENTS,
            ссылка на которую указывается на сертификате либо в социальных сетях и на сайте Продавца.</p>
        <p>4.2. Если стоимость оказанной услуги меньше номинальной цены сертификата (для сертификатов
            на сумму), сдача в денежном выражении не выдается; оставшаяся часть номинала может быть
            использована потребителем для получения иных услуг в пределах срока действия сертификата
            (п. 3 Положения № 935).</p>
        <p>4.3. В случае, если оставшейся суммы по сертификату недостаточно для оплаты выбранной услуги,
            потребитель вправе доплатить недостающую сумму любым доступным способом оплаты.</p>
        <p>4.4. Сертификат подлежит бережному хранению потребителем. Продавец не несет ответственности
            за утрату, повреждение или использование сертификата третьими лицами при отсутствии
            возможности достоверно установить недобросовестность его предъявителя.</p>

        <h2>5. Скидки за количество посещений</h2>
        <p>5.1. При приобретении сертификата на количество посещений (сеансов) применяются следующие
            скидки от стоимости услуг, включенных в сертификат:</p>
        <ul>
            <li>от 8 посещений — скидка 5%;</li>
            <li>от 12 посещений — скидка 10%.</li>
        </ul>
        <p>5.2. Скидка, предусмотренная настоящим разделом, применяется исключительно к стоимости услуг
            в рамках сертификата и не суммируется с иными акциями и скидками Продавца, если иное
            не указано отдельно.</p>

        <h2>6. Срок действия сертификата и последствия его истечения</h2>
        <p>6.1. Срок действия сертификата составляет 3 (три) месяца с даты его реализации, если иной срок
            не указан на конкретном сертификате.</p>
        <p>6.2. Ответственность за соблюдение срока действия сертификата и своевременное его использование
            несет потребитель. Продавец не обязан дополнительно уведомлять потребителя о приближении даты
            окончания срока действия сертификата, поскольку срок действия четко и заблаговременно указан
            на самом сертификате в момент его приобретения.</p>
        <p>6.3. По истечении срока действия сертификата Продавец вправе отказать потребителю в оказании
            услуг по такому сертификату. Денежные средства, уплаченные за сертификат, срок действия
            которого истек, потребителю не возвращаются (п. 3 Положения № 935; разъяснение Министерства
            антимонопольного регулирования и торговли Республики Беларусь от 2023 г. по вопросам применения
            Положения № 935, размещенное на официальном сайте mart.gov.by).</p>
        <p>6.4. Возврат денежных средств за сертификат с истекшим сроком действия является правом,
            а не обязанностью Продавца, и может быть произведен Продавцом в исключительных случаях
            по его собственному усмотрению.</p>

        <h2>7. Возврат денежных средств до истечения срока действия сертификата и при частичном использовании</h2>
        <p>7.1. В соответствии с частью второй пункта 3 Положения № 935 Продавец вправе самостоятельно
            устанавливать порядок и (или) условия реализации и использования подарочных сертификатов.
            Согласно официальному разъяснению Министерства антимонопольного регулирования и торговли
            Республики Беларусь, Положением № 935 не установлена обязанность продавца (исполнителя)
            возвращать денежные средства, уплаченные за подарочный сертификат, в связи с чем данный
            вопрос продавец вправе урегулировать самостоятельно.</p>
        <p>7.2. Пользуясь правом, предусмотренным пунктом 7.1 настоящего Положения, Продавец устанавливает:
            сертификат (в том числе срок действия которого не истек) обмену на денежные средства не подлежит —
            ни полностью, ни в части, оставшейся неиспользованной, независимо от причины отказа потребителя
            от использования сертификата (в том числе если использована лишь часть сертификата на сумму
            либо часть посещений по сертификату на количество посещений).</p>
        <p>7.3. Установленный настоящим разделом порядок доводится до сведения потребителя при приобретении
            сертификата (путем указания соответствующей информации на бланке сертификата, кассовом документе
            либо ссылкой на настоящее Положение, размещенное в общедоступном месте) и является условием
            договора между Продавцом и потребителем, заключаемого путем приобретения сертификата.</p>

        <h2>8. Дополнительные услуги</h2>
        <p>8.1. Доставка сертификата по г. Могилеву осуществляется бесплатно при номинальной стоимости
            сертификата от 400 (четырехсот) белорусских рублей. При меньшей стоимости доставка
            осуществляется на условиях, согласованных с потребителем дополнительно.</p>

        <h2>9. Заключительные положения</h2>
        <p>9.1. Настоящее Положение является локальным нормативным правовым актом Продавца, размещается
            в открытом доступе (на информационном стенде, сайте, в системе онлайн-записи и (или) социальных
            сетях Продавца) и обязательно для Продавца и потребителей, приобретающих сертификаты.</p>
        <p>9.2. Продавец вправе вносить изменения в настоящее Положение. Изменения не имеют обратной силы
            в отношении сертификатов, приобретенных до вступления изменений в силу, за исключением случаев,
            когда изменения улучшают положение потребителя.</p>
        <p>9.3. Во всем, что не урегулировано настоящим Положением, стороны руководствуются
            законодательством Республики Беларусь.</p>

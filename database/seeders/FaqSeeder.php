<?php

declare(strict_types=1);

namespace Database\Seeders;

use App\Models\Faq;
use Illuminate\Database\Seeder;

class FaqSeeder extends Seeder
{
    public function run(): void
    {
        $items = [
            ['slug' => 'booking', 'question' => 'Как записаться на сеанс?', 'answer' => 'Приём только по предварительной записи через YClients. Нажмите «Записаться онлайн» — выберите мастера, удобный день и время. Так мы гарантируем, что мастер уделит внимание только вам.'],
            ['slug' => 'duration-price', 'question' => 'Сколько длится сеанс и сколько стоит?', 'answer' => 'Сеанс — от 40 минут до полутора часов, стоимость от 50 р. Точную цену и длительность выбранной услуги вы увидите при записи в YClients.'],
            ['slug' => 'choose-master', 'question' => 'Можно ли выбрать конкретного мастера?', 'answer' => 'Да. У каждого мастера своя страница записи. Выберите специалиста в разделе «Наши мастера» и запишитесь напрямую к нему.'],
            ['slug' => 'zones', 'question' => 'Можно сделать акцент на определённые зоны?', 'answer' => 'Конечно. Мы работаем по вашему запросу: только спина и шея, ноги, полный релакс всего тела — интенсивность и акценты подбираем под ваше состояние.'],
            ['slug' => 'certificates', 'question' => 'Есть ли подарочные сертификаты?', 'answer' => 'Да. Сертификат можно оформить на определённую сумму или на количество посещений — получатель сам выберет услугу, мастера и время. При заказе от 400 р доставим сертификат по Могилёву бесплатно. Оформить можно через Instagram @hands.mg.'],
            ['slug' => 'location', 'question' => 'Где вы находитесь?', 'answer' => 'Могилёв, переулок Пожарный, 3Б. Точку на карте можно посмотреть в разделе «Как нас найти».'],
        ];

        // Ключ — slug. Старые записи (без slug, по тексту вопроса) подхватываем и
        // проставляем им slug, чтобы не задублировать.
        foreach ($items as $i => $item) {
            $faq = Faq::query()->where('slug', $item['slug'])->first()
                ?? Faq::query()->whereNull('slug')->where('question', $item['question'])->first()
                ?? new Faq;

            $faq->fill([
                'slug' => $item['slug'],
                'question' => $item['question'],
                'answer' => $item['answer'],
                'sort_order' => $i + 1,
                'is_active' => true,
            ])->save();
        }
    }
}
